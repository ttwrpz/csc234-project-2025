import 'package:freezed_annotation/freezed_annotation.dart';

import 'tier.dart';

part 'pattern_result.freezed.dart';
part 'pattern_result.g.dart';

/// Per-day Pattern Engine output. Persisted at
/// `users/{uid}/patterns/{dateId}` by the data layer.
///
/// Field nullability:
///  * `mannKendallZ` - null when the user has fewer than 14 days of history.
///  * `zScoreToday` - null when n_baseline < 14 OR σ_30 ≈ 0.
///  * `triggeredTier` - null = no algorithm fired.
///
/// `schemaV` defaults to 1; bump if the on-the-wire shape changes.
///
/// Pure-Dart entity - only imports `freezed_annotation`. JSON round-trip is
/// generated by `json_serializable` for the Firestore datasource.
@freezed
abstract class PatternResult with _$PatternResult {
  const factory PatternResult({
    required String dateId,
    required double? mannKendallZ,
    required int slidingNegCount,
    required int consecutiveHighIntensity,
    required double? zScoreToday,
    required double cusumC,
    required Tier? triggeredTier,
    @Default(1) int schemaV,
  }) = _PatternResult;

  factory PatternResult.fromJson(Map<String, Object?> json) =>
      _$PatternResultFromJson(json);
}
